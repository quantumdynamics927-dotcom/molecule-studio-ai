const App: React.FC = () => {
  // Core state
  const [activeTab, setActiveTab] = useState<TabId>('viewer');
  const [query, setQuery] = useState('');
  const [data, setData] = useState<MoleculeData | null>(null);
  const [status, setStatus] = useState<AppStatus>(AppStatus.IDLE);
  const [error, setError] = useState<string | null>(null);
  const [isRotating, setIsRotating] = useState(true);
  const [isDarkMode, setIsDarkMode] = useState(false);
  const [isAnalysisMode, setIsAnalysisMode] = useState(false);
  const [apiConnected, setApiConnected] = useState(true);

  // Export dropdown
  const [exportOpen, setExportOpen] = useState(false);
  const exportRef = useRef<HTMLDivElement>(null);

  // Toast notifications
  const [toasts, setToasts] = useState<Toast[]>([]);

  // Notebooks
  const [notebooks, setNotebooks] = useState<NotebookEntry[]>([
    { id: 'nb1', name: 'Caffeine Analysis', timestamp: Date.now() - 86400000, moleculeName: 'Caffeine' },
    { id: 'nb2', name: 'Aspirin Study', timestamp: Date.now() - 172800000, moleculeName: 'Aspirin' },
  ]);
  const [activeNotebook, setActiveNotebook] = useState<string | null>(null);

  // Database search
  const [dbSearchQuery, setDbSearchQuery] = useState('');
  const [dbResults, setDbResults] = useState<PubChemResult[]>([]);
  const [isSearchingDb, setIsSearchingDb] = useState(false);

  // Add toast helper
  const addToast = useCallback((message: string, type: ToastType = 'info') => {
    const id = generateId();
    setToasts(prev => [...prev, { id, message, type }]);
  }, []);

  const dismissToast = useCallback((id: string) => {
    setToasts(prev => prev.filter(t => t.id !== id));
  }, []);

  // Handlers
  const handleSearch = useCallback(async (searchQuery: string) => {
    if (!searchQuery.trim()) return;

    setStatus(AppStatus.LOADING);
    setError(null);

    try {
      const result = await fetchMoleculeData(searchQuery);
      setData(result);
      setStatus(AppStatus.SUCCESS);
      setApiConnected(true);
      addToast(`Loaded: ${result.name}`, 'success');
    } catch (err) {
      console.error(err);
      setError(err instanceof Error ? err.message : 'Failed to generate molecule.');
      setStatus(AppStatus.ERROR);
      setApiConnected(false);
      addToast('Failed to load molecule', 'error');
    }
  }, [addToast]);

  const handleExport = useCallback((format: ExportFormat) => {
    if (!data) {
      addToast('No molecule loaded to export', 'error');
      return;
    }
    try {
      const content = exportMolecule(data, format);
      const filename = `${data.name.toLowerCase().replace(/\s+/g, '-')}${EXPORT_FORMATS.find(f => f.format === format)?.ext}`;
      const mimeType = format === 'json' ? 'application/json' : 'chemical/x-pdb';
      downloadFile(content, filename, mimeType);
      addToast(`Exported as ${format.toUpperCase()}`, 'success');
    } catch {
      addToast('Export failed', 'error');
    }
    setExportOpen(false);
  }, [data, addToast]);

  const handleDbSearch = useCallback(async () => {
    if (!dbSearchQuery.trim()) return;
    setIsSearchingDb(true);
    setDbResults([]);

    // Simulated PubChem search - in production, use actual PubChem API
    await new Promise(resolve => setTimeout(resolve, 800));

    const mockResults: PubChemResult[] = [
      { cid: 2519, name: dbSearchQuery + ' (Sample)', formula: 'C8H10N4O2' },
      { cid: 2964, name: 'Related Compound A', formula: 'C7H8N4O2' },
      { cid: 71274, name: 'Derivative Compound', formula: 'C9H12N4O2' },
    ].filter(r => r.name.toLowerCase().includes(dbSearchQuery.toLowerCase()) || dbSearchQuery.length > 2);

    if (mockResults.length === 0) {
      mockResults.push({ cid: 2519, name: dbSearchQuery, formula: 'C8H10N4O2' });
    }

    setDbResults(mockResults);
    setIsSearchingDb(false);
    addToast(`Found ${mockResults.length} results`, 'info');
  }, [dbSearchQuery, addToast]);

  const handleDbSelect = useCallback((result: PubChemResult) => {
    setActiveTab('viewer');
    handleSearch(result.name);
  }, [handleSearch]);

  const handleCreateNotebook = useCallback(() => {
    if (!data) {
      addToast('Load a molecule first', 'error');
      return;
    }
    const newNb: NotebookEntry = {
      id: generateId(),
      name: `${data.name} Notebook`,
      timestamp: Date.now(),
      moleculeName: data.name,
    };
    setNotebooks(prev => [newNb, ...prev]);
    setActiveNotebook(newNb.id);
    setActiveTab('notebooks');
    addToast('Notebook created', 'success');
  }, [data, addToast]);

  const handleDeleteNotebook = useCallback((id: string) => {
    setNotebooks(prev => prev.filter(nb => nb.id !== id));
    if (activeNotebook === id) setActiveNotebook(null);
    addToast('Notebook deleted', 'info');
  }, [activeNotebook, addToast]);

  const handleLaunchAnalysis = useCallback((moduleId: string) => {
    if (!data) {
      addToast('Load a molecule first', 'error');
      return;
    }
    setActiveTab('viewer');
    setIsAnalysisMode(true);
    addToast(`Launched ${ANALYSIS_MODULES.find(m => m.id === moduleId)?.name}`, 'success');
  }, [data, addToast]);

  // Effects
  useEffect(() => {
    handleSearch('Caffeine');
  }, [handleSearch]);

  useEffect(() => {
    const handleClickOutside = (e: MouseEvent) => {
      if (exportRef.current && !exportRef.current.contains(e.target as Node)) {
        setExportOpen(false);
      }
    };
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  useEffect(() => {
    if (isDarkMode) {
      document.documentElement.classList.add('dark');
    } else {
      document.documentElement.classList.remove('dark');
    }
  }, [isDarkMode]);

  // Derived
  const tabs: { id: TabId; label: string; icon: React.ReactNode }[] = [
    { id: 'viewer', label: '3D Viewer', icon: <Eye size={18} /> },
    { id: 'analysis', label: 'Analysis', icon: <BarChart3 size={18} /> },
    { id: 'notebooks', label: 'Notebooks', icon: <FileText size={18} /> },
    { id: 'database', label: 'Molecule DB', icon: <Database size={18} /> },
  ];

  return (
    <div className={`relative w-full h-screen overflow-hidden flex flex-col transition-colors ${
      isDarkMode ? 'bg-stone-900' : 'bg-stone-50'
    }`}>
      {/* Background decoration */}
      <div className="absolute top-[-10%] left-[-10%] w-[40%] h-[40%] bg-blue-100 rounded-full blur-[120px] opacity-40 pointer-events-none" />
      <div className="absolute bottom-[-10%] right-[-10%] w-[40%] h-[40%] bg-red-100 rounded-full blur-[120px] opacity-40 pointer-events-none" />

      {/* Toast Container */}
      <div className="fixed top-20 right-4 z-50 space-y-2">
        {toasts.map(toast => (
          <ToastNotification key={toast.id} toast={toast} onDismiss={dismissToast} />
        ))}
      </div>

      {/* Header */}
      <header className={`relative z-10 px-6 py-4 flex items-center justify-between border-b backdrop-blur-md ${
        isDarkMode ? 'border-stone-700 bg-stone-900/50' : 'border-stone-200 bg-white/50'
      }`}>
        <div className="flex items-center gap-3">
          <div className="bg-stone-900 p-2 rounded-xl text-white">
            <Beaker size={24} />
          </div>
          <div>
            <h1 className={`text-xl font-bold tracking-tight ${isDarkMode ? 'text-white' : 'text-stone-900'}`}>
              Molecule Studio
            </h1>
            <p className="text-[10px] uppercase tracking-widest font-bold text-stone-400">GenAI Visualizer</p>
          </div>
        </div>

        {/* Tabs */}
        <div className="flex items-center gap-2 px-4 py-1.5 bg-stone-100/50 rounded-2xl">
          {tabs.map(tab => (
            <TabButton
              key={tab.id}
              id={tab.id}
              label={tab.label}
              icon={tab.icon}
              active={activeTab === tab.id}
              onClick={() => setActiveTab(tab.id)}
            />
          ))}
        </div>

        {/* Right toolbar */}
        <div className="flex items-center gap-3">
          {/* DB Search (separate from main generator search) */}
          <div className="relative hidden lg:block">
            <input
              type="text"
              value={dbSearchQuery}
              onChange={(e) => setDbSearchQuery(e.target.value)}
              onKeyDown={(e) => e.key === 'Enter' && handleDbSearch()}
              placeholder="Search PubChem..."
              className={`w-48 bg-white border border-stone-200 rounded-xl py-2 pl-4 pr-10 text-sm text-stone-800 placeholder:text-stone-400 focus:outline-none focus:ring-2 focus:ring-stone-900/10 focus:border-stone-400 transition-all`}
            />
            <button
              onClick={handleDbSearch}
              disabled={isSearchingDb}
              className="absolute right-2 top-1/2 -translate-y-1/2 text-stone-400 hover:text-stone-900 transition-colors"
            >
              {isSearchingDb ? <Loader2 className="animate-spin" size={14} /> : <Search size={14} />}
            </button>
          </div>

          {/* Export Dropdown */}
          <div className="relative" ref={exportRef}>
            <button
              onClick={() => setExportOpen(!exportOpen)}
              className={`flex items-center gap-2 px-3 py-2 rounded-xl font-medium text-sm transition-all ${
                exportOpen
                  ? 'bg-stone-900 text-white'
                  : `border ${isDarkMode ? 'border-stone-600 text-stone-300 hover:text-white hover:border-stone-500' : 'border-stone-200 text-stone-600 hover:text-stone-900 hover:border-stone-400'}`
              }`}
            >
              <Download size={16} />
              Export
              <ChevronDown size={14} className={`transition-transform ${exportOpen ? 'rotate-180' : ''}`} />
            </button>
            {exportOpen && (
              <div className={`absolute right-0 mt-2 w-48 rounded-xl shadow-lg border overflow-hidden ${
                isDarkMode ? 'bg-stone-800 border-stone-600' : 'bg-white border-stone-200'
              }`}>
                {EXPORT_FORMATS.map(({ format, label }) => (
                  <button
                    key={format}
                    onClick={() => handleExport(format)}
                    className={`w-full px-4 py-2.5 text-sm text-left flex items-center gap-2 hover:bg-stone-100 transition-colors ${
                      isDarkMode ? 'text-stone-200 hover:bg-stone-700' : 'text-stone-700'
                    }`}
                  >
                    <Table2 size={14} />
                    {label}
                  </button>
                ))}
              </div>
            )}
          </div>

          {/* Analysis Mode Toggle */}
          <button
            onClick={() => setIsAnalysisMode(!isAnalysisMode)}
            className={`p-2 rounded-xl border transition-all ${isAnalysisMode ? 'bg-amber-500 text-white border-amber-500' : isDarkMode ? 'border-stone-600 text-stone-300 hover:text-white' : 'border-stone-200 text-stone-600 hover:text-stone-900'}`}
            title="Analysis Mode"
          >
            <FlaskConical size={20} />
          </button>

          {/* Dark Mode Toggle */}
          <button
            onClick={() => setIsDarkMode(!isDarkMode)}
            className={`p-2 rounded-xl border transition-all ${isDarkMode ? 'border-stone-600 text-yellow-400 hover:text-yellow-300' : 'border-stone-200 text-stone-600 hover:text-stone-900'}`}
            title="Dark Mode"
          >
            {isDarkMode ? <Sun size={20} /> : <Moon size={20} />}
          </button>

          <div className={`h-6 w-px ${isDarkMode ? 'bg-stone-700' : 'bg-stone-200'}`} />

          <ConnectionStatus connected={apiConnected} />

          <a href="https://github.com" target="_blank" className={`${isDarkMode ? 'text-stone-400 hover:text-white' : 'text-stone-400 hover:text-stone-900'} transition-colors`}>
            <Github size={20} />
          </a>
        </div>
      </header>

      {/* Main Content */}
      <main className="flex-1 relative flex">
        {/* Left Sidebar */}
        <aside className={`relative z-10 w-80 p-6 overflow-y-auto backdrop-blur-sm border-r ${
          isDarkMode ? 'border-stone-700 bg-stone-900/30' : 'border-stone-100 bg-white/40'
        }`}>
          {activeTab === 'viewer' && (
            <ViewerSidebar data={data} status={status} error={error} onSearch={handleSearch} />
          )}
          {activeTab === 'analysis' && (
            <AnalysisSidebar onLaunch={handleLaunchAnalysis} />
          )}
          {activeTab === 'notebooks' && (
            <NotebooksSidebar
              notebooks={notebooks}
              activeNotebook={activeNotebook}
              onSelect={setActiveNotebook}
              onCreate={handleCreateNotebook}
              onDelete={handleDeleteNotebook}
            />
          )}
          {activeTab === 'database' && (
            <DatabaseSidebar
              searchQuery={dbSearchQuery}
              onSearchChange={setDbSearchQuery}
              onSearch={handleDbSearch}
              results={dbResults}
              isSearching={isSearchingDb}
              onSelect={handleDbSelect}
            />
          )}
        </aside>

        {/* Right Content */}
        <section className={`flex-1 relative ${isDarkMode ? 'bg-stone-800/30' : 'bg-stone-100/30'}`}>
          {/* Watermark */}
          <div className="absolute inset-0 flex items-center justify-center pointer-events-none opacity-[0.03] select-none">
            <h1 className={`text-[20vw] font-black uppercase ${isDarkMode ? 'text-white' : 'text-stone-900'}`}>LAB</h1>
          </div>

          {/* Analysis Mode Banner */}
          {isAnalysisMode && data && (
            <div className="absolute top-4 left-1/2 -translate-x-1/2 z-20 px-6 py-2 bg-amber-500 text-white font-bold text-sm rounded-full shadow-lg flex items-center gap-2">
              <FlaskConical size={16} />
              Analysis Mode Active — {ANALYSIS_MODULES[0]?.name || 'Module'}
            </div>
          )}

          {/* Loading overlay */}
          {status === AppStatus.LOADING && (
            <div className={`absolute inset-0 z-20 backdrop-blur-sm flex flex-col items-center justify-center gap-4 ${
              isDarkMode ? 'bg-stone-900/50' : 'bg-stone-50/50'
            }`}>
              <div className="relative">
                <div className="w-16 h-16 border-4 border-stone-200 border-t-stone-900 rounded-full animate-spin" />
                <div className="absolute inset-0 flex items-center justify-center">
                  <Beaker className="text-stone-900" size={24} />
                </div>
              </div>
              <div className="text-center">
                <p className="font-bold text-stone-900">Synthesizing structure...</p>
                <p className="text-xs text-stone-400">Gemini is calculating atomic coordinates</p>
              </div>
            </div>
          )}

          {/* 3D Canvas */}
          <div className="w-full h-full cursor-grab active:cursor-grabbing">
            <MoleculeCanvas data={data} isRotating={isRotating} />
          </div>

          {/* Controls hint */}
          <div className="absolute bottom-8 right-8 flex gap-4">
            <div className={`flex items-center gap-4 backdrop-blur px-4 py-2 rounded-2xl shadow-sm border text-[10px] font-bold uppercase tracking-widest ${
              isDarkMode ? 'bg-stone-800/80 border-stone-600 text-stone-300' : 'bg-white/80 border-stone-200 text-stone-400'
            }`}>
              <div className="flex items-center gap-1">
                <div className={`w-4 h-4 rounded ${isDarkMode ? 'bg-stone-700 border-stone-500' : 'bg-stone-100 border-stone-300'}`} /> Orbit
              </div>
              <div className="flex items-center gap-1">
                <div className={`w-4 h-4 rounded ${isDarkMode ? 'bg-stone-700 border-stone-500' : 'bg-stone-100 border-stone-300'}`} /> Zoom
              </div>
            </div>

            {/* Auto-rotate toggle */}
            <button
              onClick={() => setIsRotating(!isRotating)}
              className={`p-2 rounded-xl border shadow-sm transition-all ${
                isRotating
                  ? 'bg-stone-900 text-white border-stone-900'
                  : isDarkMode ? 'bg-stone-800 text-stone-300 border-stone-600' : 'bg-white text-stone-600 border-stone-200'
              }`}
              title="Toggle Auto-rotation"
            >
              <RotateCw size={18} className={isRotating ? 'animate-spin-slow' : ''} />
            </button>
          </div>
        </section>
      </main>

      {/* Notebook Content Area (when notebook is active) */}
      {activeTab === 'notebooks' && activeNotebook && (
        <div className={`absolute inset-0 z-30 flex items-center justify-center ${
          isDarkMode ? 'bg-stone-900/90' : 'bg-white/90'
        }`}>
          <div className={`max-w-lg p-8 rounded-2xl border text-center ${isDarkMode ? 'bg-stone-800 border-stone-700' : 'bg-white border-stone-200'}`}>
            <FileText size={48} className={`mx-auto mb-4 ${isDarkMode ? 'text-stone-400' : 'text-stone-300'}`} />
            <h2 className={`text-xl font-bold mb-2 ${isDarkMode ? 'text-white' : 'text-stone-900'}`}>
              {notebooks.find(nb => nb.id === activeNotebook)?.name}
            </h2>
            <p className={`text-sm ${isDarkMode ? 'text-stone-400' : 'text-stone-500'}`}>
              Notebook content would appear here. Analysis results, notes, and visualizations are stored in each notebook session.
            </p>
            <button
              onClick={() => setActiveNotebook(null)}
              className="mt-4 px-4 py-2 bg-stone-900 text-white text-sm font-medium rounded-xl hover:bg-stone-800 transition-colors"
            >
              Close Notebook
            </button>
          </div>
        </div>
      )}

      <style>{`
        @keyframes spin-slow {
          from { transform: rotate(0deg); }
          to { transform: rotate(360deg); }
        }
        .animate-spin-slow {
          animation: spin-slow 8s linear infinite;
        }
        @keyframes slide-in {
          from { transform: translateX(100%); opacity: 0; }
          to { transform: translateX(0); opacity: 1; }
        }
        .animate-slide-in {
          animation: slide-in 0.3s ease-out;
        }
      `}</style>
    </div>
  );
};

export default App;
