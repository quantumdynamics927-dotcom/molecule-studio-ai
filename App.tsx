const ToastNotification: React.FC<{ toast: Toast; onDismiss: (id: string) => void }> = ({ toast, onDismiss }) => {
  useEffect(() => {
    const timer = setTimeout(() => onDismiss(toast.id), 4000);
    return () => clearTimeout(timer);
  }, [toast.id, onDismiss]);

  return (
    <div className={`flex items-center gap-3 px-4 py-3 rounded-xl shadow-lg border animate-slide-in ${
      toast.type === 'success' ? 'bg-green-50 border-green-200 text-green-800' :
      toast.type === 'error' ? 'bg-red-50 border-red-200 text-red-800' :
      'bg-blue-50 border-blue-200 text-blue-800'
    }`}>
      {toast.type === 'success' && <Check size={18} className="text-green-600" />}
      {toast.type === 'error' && <X size={18} className="text-red-600" />}
      {toast.type === 'info' && <Bell size={18} className="text-blue-600" />}
      <span className="text-sm font-medium">{toast.message}</span>
      <button onClick={() => onDismiss(toast.id)} className="ml-2 opacity-60 hover:opacity-100">
        <X size={14} />
      </button>
    </div>
  );
};

